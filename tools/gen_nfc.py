#!/usr/bin/env python3
"""Generate src/nfc_tables.h: canonical decompositions, combining classes,
and primary composites for NFC normalization."""
import sys
import unicodedata

decomp = {}      # cp -> (a, b) or (a,)
ccc = {}         # cp -> combining class (nonzero only)
for cp in range(0x110000):
    ch = chr(cp)
    c = unicodedata.combining(ch)
    if c:
        ccc[cp] = c
    d = unicodedata.decomposition(ch)
    if d and not d.startswith("<"):  # canonical only
        parts = [int(x, 16) for x in d.split()]
        decomp[cp] = tuple(parts)

# Primary composites: canonical pair decompositions not excluded from composition.
comp = {}
for cp, parts in decomp.items():
    if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
        comp[(parts[0], parts[1])] = cp

with open(sys.argv[1], "w") as f:
    f.write("// Generated by tools/gen_nfc.py — do not edit.\n")
    f.write("#pragma once\n#include <cstdint>\n\nnamespace mk {\n\n")

    f.write("struct NfcDecomp { uint32_t cp, a, b; };  // b==0: singleton\n")
    f.write("inline constexpr NfcDecomp kNfcDecomp[] = {\n")
    for cp in sorted(decomp):
        parts = decomp[cp]
        b = parts[1] if len(parts) == 2 else 0
        f.write(f"    {{0x{cp:X}, 0x{parts[0]:X}, 0x{b:X}}},\n")
    f.write("};\n\n")

    f.write("struct NfcCcc { uint32_t cp; uint8_t ccc; };\n")
    f.write("inline constexpr NfcCcc kNfcCcc[] = {\n")
    for cp in sorted(ccc):
        f.write(f"    {{0x{cp:X}, {ccc[cp]}}},\n")
    f.write("};\n\n")

    f.write("struct NfcComp { uint32_t a, b, composed; };\n")
    f.write("inline constexpr NfcComp kNfcComp[] = {  // sorted by (a, b)\n")
    for (a, b) in sorted(comp):
        f.write(f"    {{0x{a:X}, 0x{b:X}, 0x{comp[(a, b)]:X}}},\n")
    f.write("};\n\n} // namespace mk\n")

print(f"decomp: {len(decomp)}, ccc: {len(ccc)}, comp: {len(comp)}")
