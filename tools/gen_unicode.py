#!/usr/bin/env python3
"""Generate src/unicode_tables.h: codepoint ranges for \p{L}, \p{N} and White_Space."""
import sys
import unicodedata


def ranges_for(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        else:
            if start is not None:
                out.append((start, cp - 1))
                start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def cat(cp):
    return unicodedata.category(chr(cp))


letters = ranges_for(lambda cp: cat(cp).startswith("L"))
numbers = ranges_for(lambda cp: cat(cp).startswith("N"))
# White_Space property (what rust-regex \s matches). unicodedata lacks the
# property directly; the full list is small and stable.
WS = [0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680,
      *range(0x2000, 0x200B), 0x2028, 0x2029, 0x202F, 0x205F, 0x3000]
ws_ranges = []
for cp in sorted(WS):
    if ws_ranges and cp == ws_ranges[-1][1] + 1:
        ws_ranges[-1] = (ws_ranges[-1][0], cp)
    else:
        ws_ranges.append((cp, cp))


def emit(f, name, rs):
    f.write(f"inline constexpr CpRange {name}[] = {{\n")
    for a, b in rs:
        f.write(f"    {{0x{a:X}, 0x{b:X}}},\n")
    f.write("};\n\n")


with open(sys.argv[1], "w") as f:
    f.write("// Generated by tools/gen_unicode.py — do not edit.\n")
    f.write(f"// unicodedata {unicodedata.unidata_version}\n")
    f.write("#pragma once\n#include <cstdint>\n\nnamespace mk {\n\n")
    f.write("struct CpRange { uint32_t lo, hi; };\n\n")
    emit(f, "kLetterRanges", letters)
    emit(f, "kNumberRanges", numbers)
    emit(f, "kWhitespaceRanges", ws_ranges)
    f.write("} // namespace mk\n")

print(f"letters: {len(letters)} ranges, numbers: {len(numbers)}, ws: {len(ws_ranges)}")
